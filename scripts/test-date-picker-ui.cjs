const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_CORE_PATH || 'playwright-core')
const url = process.env.DATE_PICKER_TEST_URL || 'http://127.0.0.1:5173/scripts/fixtures/date-pickers.html'
const endpoint = new URL(url)
assert.ok(['127.0.0.1', 'localhost'].includes(endpoint.hostname), 'UI fixture must stay on loopback')
const browserErrors = []

async function main() {
    const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] })
    try {
        for (const width of [1280, 390, 320]) {
            const context = await browser.newContext({ viewport: { width, height: 850 }, timezoneId: 'America/Los_Angeles' })
            await context.route('**/*', route => new URL(route.request().url()).origin === endpoint.origin ? route.continue() : route.abort())
            const page = await context.newPage()
            page.on('pageerror', error => browserErrors.push(error.message))
            await page.clock.install({ time: new Date('2026-10-08T00:30:00Z') })
            await page.goto(url)
            const root = '.mantine-DatePickerInput-datePickerRoot'
            await page.getByLabel('Range fixture').click()
            const dialog = page.getByRole('dialog')
            await dialog.waitFor()
            await page.waitForTimeout(250)
            const list = dialog.locator('.mantine-DatePickerInput-presetsList')
            assert.equal(await list.locator('button').count(), 10)
            const listBox = await list.boundingBox()
            const calendarBox = await dialog.locator('table').first().boundingBox()
            assert.ok(listBox.x + listBox.width <= calendarBox.x + 2, `Presets must be LEFT of calendar at ${width}px`)
            const calendarRoot = await dialog.locator(root).boundingBox()
            await page.screenshot({ path: `/tmp/date-picker-range-${width}.png` })
            assert.ok(calendarRoot.x >= -1 && calendarRoot.x + calendarRoot.width <= width + 1, `Calendar/sidebar overflow at ${width}px`)
            await list.getByRole('button', { name: '7 天', exact: true }).click()
            assert.equal(await page.getByTestId('range-value').textContent(), '["2026-10-02","2026-10-08"]')
            await page.getByLabel('Range fixture').click()
            await page.getByRole('dialog').locator('.mantine-DatePickerInput-presetsList').getByRole('button', { name: '今天', exact: true }).click()
            assert.equal(await page.getByTestId('range-value').textContent(), '["2026-10-08","2026-10-08"]')
            await page.clock.setSystemTime(new Date('2026-10-09T00:30:00Z'))
            await page.getByLabel('Range fixture').click()
            await page.getByRole('dialog').locator('.mantine-DatePickerInput-presetsList').getByRole('button', { name: '今天', exact: true }).click()
            assert.equal(await page.getByTestId('range-value').textContent(), '["2026-10-09","2026-10-09"]', 'Reopening a long-lived picker refreshes today and maxDate')
            await page.getByLabel('Paid fixture').click()
            await page.locator('.mantine-DatePickerInput-presetsList:visible').getByRole('button', { name: '7 天前', exact: true }).click()
            assert.equal(await page.getByTestId('date-value').textContent(), '2026-10-01')
            await page.getByLabel('Expiry fixture').click()
            const expiryList = page.getByRole('dialog').locator('.mantine-DateTimePicker-presetsList')
            await expiryList.getByRole('button', { name: '+1 个月', exact: true }).click()
            assert.equal(await page.getByTestId('expiry-value').textContent(), '2026-12-30 12:15:30', 'Expiry quick choice keeps the selected time and extension base')
            const expiryRoot = await page.getByRole('dialog').locator('.mantine-DateTimePicker-datePickerRoot').boundingBox()
            assert.ok(expiryRoot.x >= -1 && expiryRoot.x + expiryRoot.width <= width + 1, `DateTime sidebar overflow at ${width}px`)
            await page.keyboard.press('Escape')
            const billList = page.locator('.mantine-DatePicker-presetsList')
            await billList.getByRole('button', { name: '+1 个月', exact: true }).click()
            assert.equal(await page.getByTestId('bill-value').textContent(), '2026-11-08')
            await context.close()
            console.log(`PASS date picker browser interaction / left sidebar / bounds / local+UTC / stale tabs / time preservation (${width}px)`)
        }
        assert.deepEqual(browserErrors, [], 'Browser must not raise runtime errors')
    } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
